String translate(BuildContext context, String text) {
  if (Localizations.maybeLocaleOf(context)?.languageCode != 'ru') return text;
  return translateRussian(text);
}

String translateRussian(String text) {
  final exact = _ru[text];
  if (exact != null) return exact;
  for (final entry in _patterns) {
    final match = entry.$1.firstMatch(text);
    if (match != null) return entry.$2(match);
  }
  return text;
}

